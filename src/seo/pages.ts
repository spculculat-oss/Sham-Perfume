/**
 * The indexable pages of the platform.
 *
 * The app itself is a hash-routed single page (`#concentration`, `#store`…), which search engines
 * cannot treat as separate URLs. «منارة شاهين» therefore maintains a real static page for each
 * major tool (tools/<slug>.html, generated at build time): title, description, H1, guide, FAQ and
 * structured data in plain HTML. Each page's call to action opens the matching tab in the app.
 *
 * AI-written copy never lands here directly: the agent proposes it in src/data/live/seo-pages.json,
 * and the build applies it only after the guardrails in src/seo/agentState.ts accept it.
 */
