/** Title/description for the SPA's runtime tabs (document.title + meta description). */
export function tabSeo(tab: string): { title: string; description: string; path: string } {
  if (tab === 'home' || !tab) return { title: HOME_PAGE.title, description: HOME_PAGE.description, path: '' };
  if (tab === 'productDetail') {
    return { title: 'منتج من متجر شام | صمم عطرك مع شام', description: 'تفاصيل المنتج ونوتاته وسعره في متجر شام، مع إمكانية الطلب مباشرة وسؤال الخبير شاهين.', path: '' };
  }
  if (tab === 'community') {
    return { title: 'مجتمع شام: تجار وطلبات وعروض عطور', description: 'مجتمع شام لربط التجار والعملاء: متاجر، عروض، طلبات، وصفحات تواصل داخل منصة واحدة.', path: '' };
  }
  const page = pageByTab(tab);
  return page
    ? { title: page.title, description: page.description, path: page.path }
    : { title: HOME_PAGE.title, description: HOME_PAGE.description, path: '' };
}
